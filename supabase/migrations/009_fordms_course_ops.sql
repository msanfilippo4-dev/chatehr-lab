  hits INT NOT NULL DEFAULT 0
);

CREATE OR REPLACE FUNCTION ehr_rate_limit_hit(p_bucket TEXT, p_limit INT, p_window_seconds INT) RETURNS BOOLEAN AS $$
DECLARE
  current_hits INT;
BEGIN
  INSERT INTO ehr_rate_limits (bucket, window_start, hits)
  VALUES (p_bucket, now(), 1)
  ON CONFLICT (bucket) DO UPDATE SET
    hits = CASE WHEN ehr_rate_limits.window_start < now() - make_interval(secs => p_window_seconds) THEN 1 ELSE ehr_rate_limits.hits + 1 END,
    window_start = CASE WHEN ehr_rate_limits.window_start < now() - make_interval(secs => p_window_seconds) THEN now() ELSE ehr_rate_limits.window_start END
  RETURNING hits INTO current_hits;
  RETURN current_hits <= p_limit;
END;
$$ LANGUAGE plpgsql;

