-- Widen the submission status CHECK to include revision_requested.
DO $$
DECLARE
  existing TEXT;
BEGIN
  SELECT conname INTO existing FROM pg_constraint
   WHERE conrelid = 'ehr_assignment_submissions'::regclass AND contype = 'c'
     AND pg_get_constraintdef(oid) LIKE '%status%';
  IF existing IS NOT NULL AND pg_get_constraintdef((SELECT oid FROM pg_constraint WHERE conname = existing)) NOT LIKE '%revision_requested%' THEN
    EXECUTE format('ALTER TABLE ehr_assignment_submissions DROP CONSTRAINT %I', existing);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'ehr_assignment_submissions'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%revision_requested%') THEN
    ALTER TABLE ehr_assignment_submissions ADD CONSTRAINT ehr_assignment_submissions_status_check
      CHECK (status IN ('submitted', 'graded', 'returned', 'revision_requested'));
  END IF;
END $$;

